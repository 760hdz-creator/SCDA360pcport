"""Hashes of the game's controller-prompt icons, for runtime/src/prompts_table.inc.

usage: python -I tools/prompts/icon_hashes.py <game>/System/menu.lin > runtime/src/prompts_table.inc

menu.lin embeds the icons as DDS files (\\Textures\\Common\\button_*.dds, 64x64 / 32x32 DXT5). The
hash is FNV-1a 64 over level 0's 4x4 blocks in row order, little-endian as in the DDS file; the
runtime computes the same over a guest texture (BlockLinearHash in gpu/draw_state.cpp) to know
an icon whatever its tiling or address. Only names and hashes are written, no game data.
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from lin_inflate import inflate  # noqa: E402

# Icons runtime/src/prompts.cpp redraws (button_black/white/glow/none and buttonwhite are plain
# shapes the game tints: left alone).
NAMES = [
    'button_a', 'button_b', 'button_x', 'button_y', 'button_back', 'button_start',
    'button_lb', 'button_rb', 'button_rb_lb', 'button_lt', 'button_rt', 'button_rt_lt',
    'button_ls', 'button_ls_u', 'button_ls_d', 'button_ls_l', 'button_ls_r', 'button_ls_u_d',
    'button_ls_l_r', 'button_ls_press', 'button_al', 'button_al_up', 'button_al_clic',
    'button_rs', 'button_rs_u', 'button_rs_d', 'button_rs_l', 'button_rs_r', 'button_rs_u_d',
    'button_rs_l_r', 'button_rs_press', 'button_ar', 'button_ar_clic',
    'button_d', 'button_d_u', 'button_d_d', 'button_d_l', 'button_d_r', 'button_d_u_d',
    'button_d_l_r', 'button_du', 'button_dd', 'button_dl', 'button_dr',
    'btn_opsat_a', 'btn_opsat_b',
]


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    data = inflate(open(sys.argv[1], 'rb').read())
    found = {}
    for m in re.finditer(rb'[\\/]textures[\\/]common[\\/]([A-Za-z0-9_]+)\.dds', data, re.I):
        name = m.group(1).decode().lower()
        p = data.find(b'DDS |', m.end(), m.end() + 32)
        if name not in NAMES or name in found or p < 0:
            continue
        height, width = struct.unpack_from('<II', data, p + 12)
        fourcc = data[p + 84:p + 88]
        if fourcc != b'DXT5':
            continue
        size = (width // 4) * (height // 4) * 16
        found[name] = (width, height, fnv1a64(data[p + 128:p + 128 + size]))
    missing = [n for n in NAMES if n not in found]
    if missing:
        sys.exit('missing: ' + ', '.join(missing))
    print('// Generated by tools/prompts/icon_hashes.py from menu.lin: { name, width, height, hash }.')
    for n in NAMES:
        w, h, v = found[n]
        print('{ "%s", %d, %d, 0x%016XULL },' % (n, w, h, v))


if __name__ == '__main__':
    main()
